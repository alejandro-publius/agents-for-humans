"""make site: the evidence as a static site a judge can open, built from the documents this package ships.

One page per document (the README, every shipped document under docs/, the evidence packets, the posts, the
video commands, the screenshots index, the reports), the diagrams in place of the Mermaid blocks, the
screenshots as a gallery on the front page, the claims badge, and every `docs/...md` mention turned into a
link. No script, no network, no tracking: HTML and PNG files under build/site/, the same on every run, ready
for GitHub Pages (`.github/workflows/pages.yml` publishes it from main once Pages is switched on in the
repository settings) or for any static host. Nothing here is a result: the pages say what the documents say.

    python scripts/site.py                # build/site/index.html and the rest
    python scripts/site.py --out <dir>    # elsewhere
"""

